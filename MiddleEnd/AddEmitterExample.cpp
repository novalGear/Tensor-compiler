// AddEmitter.cpp
// Полный пример генерации MLIR для операции сложения с подробными комментариями

#include "AddEmitter.h"
#include "mlir/Dialect/Linalg/IR/Linalg.h"
#include "mlir/Dialect/Arith/IR/Arith.h"
#include "mlir/Dialect/Tensor/IR/Tensor.h"

namespace tcc {
namespace mlir_gen {

mlir::Value AddEmitter::emit(const std::vector<mlir::Value>& inputs,
                              const std::vector<std::string>& outputNames,
                              const std::vector<size_t>& outputDims) {

    // ================================================================
    // ШАГ 1: Получение контекста и location
    // ================================================================
    // Location в MLIR — это информация об исходном коде (файл, строка)
    // Для сгенерированного кода используем UnknownLoc
    auto loc = mlir::UnknownLoc::get(builder.getContext());

    // ================================================================
    // ШАГ 2: Проверка входных данных
    // ================================================================
    // Операция сложения требует ровно два входных тензора
    assert(inputs.size() == 2 && "Add operation requires exactly 2 inputs");

    // ================================================================
    // ШАГ 3: Получение типов входных тензоров
    // ================================================================
    // Каждый тензор в MLIR имеет тип RankedTensorType, который содержит:
    // - размерности (shape)
    // - тип элементов (например, f32)
    auto lhsType = inputs[0].getType().cast<mlir::RankedTensorType>();
    auto rhsType = inputs[1].getType().cast<mlir::RankedTensorType>();

    // Тип элемента должен быть одинаковым для обоих входов
    // В нашем случае все тензоры хранят float32
    auto elementType = lhsType.getElementType();

    // ================================================================
    // ШАГ 4: Создание типа результата
    // ================================================================
    // Результат сложения — тензор той же размерности, что и входы
    // Размерности передаются из графа (outputDims)
    llvm::SmallVector<int64_t> mlirDims;
    for (auto dim : outputDims) {
        mlirDims.push_back(static_cast<int64_t>(dim));
    }

    auto resultType = mlir::RankedTensorType::get(mlirDims, elementType);

    // ================================================================
    // ШАГ 5: Создание пустого тензора для результата
    // ================================================================
    // В MLIR тензоры immutable (неизменяемые). Операция linalg.generic
    // требует выходной буфер, который будет заполнен.
    // tensor.empty создает "пустой" тензор без инициализированных значений.
    // Реальные значения будут записаны внутри linalg.generic.
    auto empty = builder.create<mlir::tensor::EmptyOp>(
        loc,                    // location
        mlirDims,               // размерности тензора
        elementType             // тип элементов
    );

    // ================================================================
    // ШАГ 6: Создание индексных мап (indexing maps)
    // ================================================================
    // Индексные мапы определяют, как индексы итераторов отображаются
    // на индексы входных и выходных тензоров.
    //
    // Для поэлементного сложения с размерностью 2 (например, матрица 2x3):
    // Итераторы: d0 (первая размерность), d1 (вторая размерность)
    // Мапа для LHS: (d0, d1) -> (d0, d1) — берем элемент на тех же позициях
    // Мапа для RHS: (d0, d1) -> (d0, d1) — аналогично
    // Мапа для результата: (d0, d1) -> (d0, d1) — записываем на те же позиции
    //
    // getIdentityIndexingMaps создает identity мапы для каждого операнда
    auto identityMaps = mlir::linalg::getIdentityIndexingMaps(
        builder,                // билдер для создания аффинных выражений
        resultType.getRank()    // количество размерностей (ранг)
    );

    // ================================================================
    // ШАГ 7: Определение типов итераторов
    // ================================================================
    // В linalg.generic итераторы могут быть:
    // - parallel: итерации независимы и могут выполняться параллельно
    // - reduction: итерации сводятся к одному значению (например, суммирование)
    //
    // Для поэлементного сложения все итерации независимы → parallel
    llvm::SmallVector<mlir::utils::IteratorType> iteratorTypes(
        resultType.getRank(),           // количество итераторов = ранг тензора
        mlir::utils::IteratorType::parallel
    );

    // ================================================================
    // ШАГ 8: Создание операции linalg.generic
    // ================================================================
    // linalg.generic — это структурированная операция, которая описывает
    // вычисления над тензорами в виде:
    // - входные тензоры (inputs)
    // - выходные тензоры (outputs, в нашем случае пустой тензор)
    // - индексные мапы
    // - типы итераторов
    // - тело операции (регион с базовыми арифметическими операциями)
    auto generic = builder.create<mlir::linalg::GenericOp>(
        loc,                    // location
        resultType,             // тип результата
        inputs,                 // список входных тензоров (LHS, RHS)
        empty,                  // выходной буфер (один)
        identityMaps,           // индексные мапы для всех операндов
        iteratorTypes           // типы итераторов
    );

    // ================================================================
    // ШАГ 9: Создание тела операции (регион)
    // ================================================================
    // linalg.generic содержит регион (область кода), который выполняется
    // для каждой точки итерационного пространства.
    //
    // Регион получает аргументы:
    // - аргументы для каждого входного тензора (по одному на вход)
    // - аргументы для каждого выходного тензора (один)
    // В нашем случае: arg0 (элемент LHS), arg1 (элемент RHS), arg2 (выход)

    // Получаем регион операции и очищаем его (он пустой по умолчанию)
    mlir::Region& region = generic.getRegion();
    region.push_back(new mlir::Block);  // добавляем блок в регион
    mlir::Block& block = region.front();

    // Добавляем аргументы блока:
    // - аргумент 0: элемент из LHS тензора (тип f32)
    // - аргумент 1: элемент из RHS тензора (тип f32)
    // - аргумент 2: выходной элемент (тип f32) — будет перезаписан
    block.addArguments(elementType, loc);  // arg0
    block.addArguments(elementType, loc);  // arg1
    block.addArguments(elementType, loc);  // arg2 (output)

    // Устанавливаем точку вставки внутрь блока
    mlir::OpBuilder::InsertionGuard guard(builder);
    builder.setInsertionPointToStart(&block);

    // ================================================================
    // ШАГ 10: Генерация тела операции
    // ================================================================
    // Внутри блока мы создаем арифметическую операцию сложения
    auto arg0 = block.getArgument(0);  // элемент LHS
    auto arg1 = block.getArgument(1);  // элемент RHS

    // arith.addf — скалярное сложение чисел с плавающей точкой
    auto sum = builder.create<mlir::arith::AddFOp>(loc, arg0, arg1);

    // linalg.yield возвращает результат из блока
    // Значение sum будет записано в выходной тензор на текущей позиции
    builder.create<mlir::linalg::YieldOp>(loc, sum);

    // ================================================================
    // ШАГ 11: Сохранение результата
    // ================================================================
    // linalg.generic возвращает значение — тензор с результатом
    auto result = generic.getResult(0);

    // Сохраняем результат в карту тензоров, чтобы последующие операции
    // могли использовать этот тензор как входной
    // outputNames[0] — имя выходного тензора из графа (например, "add_output")
    tensorMap[outputNames[0]] = result;

    // ================================================================
    // ШАГ 12: Возврат результата
    // ================================================================
    // Возвращаем MLIR значение, хотя вызывающий код может его не использовать,
    // так как результат уже сохранен в tensorMap
    return result;
}

} // namespace mlir_gen
} // namespace tcc
